"""voice_env.py: voice envelope and word timings for lip-sync and dynamic subtitles (songs or speech).

Reads an audio file and the LY lines in src/lyrics.js ([start, end, "text"], words split by spaces and |), and writes
src/voice.js with:
  VOX(t)  0..1 mouth-open envelope at --fps (300-3000 Hz voice band; RMS plus onset pulses), zero outside lines
  LYW[i]  start time of every word of LY[i] (cumulative voice energy warped to syllable counts, snapped to onsets)

Run from the project root:
  python3 scripts/voice_env.py --audio assets/song.mp3
  python3 scripts/voice_env.py --audio assets/vo.wav --speech --syl "AGI=3,ChatGPT=4"
Flags: --lyrics src/lyrics.js  --out src/voice.js  --fps 24
       --speech  skip the harmonic split (spoken voice; keep it for singing over music)
       --syl     syllable counts for acronyms and names the vowel rule gets wrong
Needs: pip install librosa numpy
"""
import argparse, json, re, pathlib
import numpy as np, librosa

ap = argparse.ArgumentParser()
ap.add_argument('--audio', required=True)
ap.add_argument('--lyrics', default='src/lyrics.js')
ap.add_argument('--out', default='src/voice.js')
ap.add_argument('--fps', type=int, default=24)
ap.add_argument('--speech', action='store_true')
ap.add_argument('--syl', default='')
A = ap.parse_args()

SR, FPS = 22050, A.fps
HOP = SR // FPS  # one hop per video frame
ACR = {k: int(v) for k, v in (p.split('=') for p in A.syl.split(',') if '=' in p)}

src = pathlib.Path(A.lyrics).read_text()
LY = [(float(a), float(b), s) for a, b, s in re.findall(r'\[\s*([\d.]+),\s*([\d.]+),\s*"((?:[^"\\]|\\.)*)"\s*\]', src)]

y, _ = librosa.load(A.audio, sr=SR, mono=True)
if not A.speech: y, _ = librosa.effects.hpss(y, margin=2.0)
S = np.abs(librosa.stft(y, n_fft=2048, hop_length=HOP))
f = librosa.fft_frequencies(sr=SR, n_fft=2048)
Sb = S[(f >= 300) & (f <= 3000)]
rms = np.sqrt((Sb ** 2).mean(axis=0))
onset = librosa.onset.onset_strength(S=librosa.amplitude_to_db(Sb, ref=np.max), sr=SR, hop_length=HOP)
n = int(np.ceil(len(y) / HOP))
rms, onset = np.pad(rms, (0, max(0, n - len(rms))))[:n], np.pad(onset, (0, max(0, n - len(onset))))[:n]
tt = np.arange(n) / FPS

def words_of(s):  # same split as subs.js: spaces, then | inside a group
    return [w for g in s.split(' ') if g for w in g.split('|')]

def syl(w):
    if w in ACR: return ACR[w]
    core = re.sub(r'[^a-z]', '', w.lower())
    if not core: return max(1, round(len(re.sub(r'\W', '', w)) / 3))  # non-Latin script: about 3 letters a syllable
    k = len(re.findall(r'[aeiouy]+', core))
    if core.endswith('e') and not core.endswith(('le', 'ee')) and k > 1: k -= 1
    return max(1, k)

vox, LYW = np.zeros(n), []
for a, b, s in LY:
    i0, i1 = int(a * FPS), min(n, int(np.ceil(b * FPS)) + 1)
    r, o = rms[i0:i1], onset[i0:i1]
    rn = (r - np.percentile(r, 10)) / (np.percentile(r, 95) - np.percentile(r, 10) + 1e-9)
    on = o / (np.percentile(o, 97) + 1e-9)
    v = np.convolve(np.clip(.75 * np.clip(rn, 0, 1) + .5 * np.clip(on, 0, 1), 0, 1), [.25, .5, .25], mode='same')
    ramp = np.clip(np.minimum(tt[i0:i1] - a, b - tt[i0:i1]) / .08, 0, 1)
    vox[i0:i1] = np.maximum(vox[i0:i1], v * ramp)
    ws = words_of(s)
    sy = np.array([syl(w) for w in ws], float)
    frac = np.concatenate([[0], np.cumsum(sy)[:-1]]) / sy.sum()
    e = np.clip(rn, 0, None) + .05
    ce = np.cumsum(e) / e.sum()
    peaks = librosa.util.peak_pick(o, pre_max=2, post_max=2, pre_avg=4, post_avg=4, delta=.3 * o.std(), wait=2)
    starts = []
    for k, fr in enumerate(frac):
        ts = a + (int(np.searchsorted(ce, fr)) if k else 0) / FPS
        if k and len(peaks):
            pt = a + peaks / FPS
            near = pt[np.abs(pt - ts) < .12]
            if len(near): ts = float(near[np.argmin(np.abs(near - ts))])
        if starts: ts = max(ts, starts[-1] + .07)
        starts.append(round(min(ts, b - .05), 3))
    LYW.append(starts)

q = ''.join(chr(48 + int(round(v * 9))) for v in vox)
pathlib.Path(A.out).write_text(f"""// voice.js: generated by scripts/voice_env.py, do not edit by hand.
// VOX(t): 0..1 mouth-open envelope at t (0 between lines). LYW[i]: start time of each word of LY[i].
const VOX_FPS = {FPS}, VOX_S = "{q}";
function VOX(t) {{
  const f = t * VOX_FPS, i = Math.floor(f), a = i >= 0 && i < VOX_S.length ? VOX_S.charCodeAt(i) - 48 : 0, b = i + 1 >= 0 && i + 1 < VOX_S.length ? VOX_S.charCodeAt(i + 1) - 48 : 0;
  return (a + (b - a) * (f - i)) / 9;
}}
const LYW = {json.dumps(LYW, separators=(',', ':'))};
""")
print('lines', len(LY), 'frames', n, 'mean vox in lines', round(float(vox[vox > 0].mean()), 3) if (vox > 0).any() else 0)
for (a, b, s), w in list(zip(LY, LYW))[:3]: print(s, w)
